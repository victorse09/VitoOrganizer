"""
Vito Organizer — Generador de Iconos SVG
Genera iconos SVG como cadenas de texto y los convierte a QIcon al vuelo.
Todos los iconos son SVG puro, sin dependencias externas.
"""

from PyQt6.QtCore import QByteArray, QSize
from PyQt6.QtGui import QIcon, QPixmap, QPainter, QColor
from PyQt6.QtSvg import QSvgRenderer


def svg_to_qicon(svg_string: str, size: int = 32, color: str | None = None) -> QIcon:
    """
    Convierte una cadena SVG en un QIcon renderizado.
    
    Args:
        svg_string: Código SVG como string.
        size: Tamaño del icono en píxeles.
        color: Color opcional para reemplazar 'currentColor' en el SVG.
    
    Returns:
        QIcon listo para usar en botones y menús.
    """
    if color:
        svg_string = svg_string.replace('currentColor', color)
    
    svg_bytes = QByteArray(svg_string.encode('utf-8'))
    renderer = QSvgRenderer(svg_bytes)
    
    pixmap = QPixmap(QSize(size, size))
    pixmap.fill(QColor(0, 0, 0, 0))  # Fondo transparente
    
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()
    
    return QIcon(pixmap)


